// Deterministic build: include exact URLs and bytes; a deployment mixing releases cannot install.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const origin='https://offline.invalid/';
const read=name=>fs.readFileSync(path.join(root,name));
const html=read('index.html').toString();
const version=html.match(/js\/main\.js\?v=([\d.]+)/)[1];
const urls=new Set(['index.html']);
function add(ref,base='index.html') {
  const u=new URL(ref,new URL(base,origin));
  if(u.origin!==new URL(origin).origin || u.hash) return;
  const name=u.pathname.slice(1)+u.search;
  if(urls.has(name))return;urls.add(name);
  const content=read(u.pathname.slice(1)).toString();
  if(u.pathname.endsWith('.js')) for(const m of content.matchAll(/(?:from\s*|import\s*)['"]([^'"]+)['"]/g)) add(m[1],name);
  if(u.pathname.endsWith('.css')) for(const m of content.matchAll(/url\(['"]?([^'"\)]+)['"]?\)/g)) add(m[1],name);
}
for(const m of html.matchAll(/(?:src|href)="([^"#]+)"/g))add(m[1]);
for(const icon of JSON.parse(read('manifest.webmanifest')).icons)add(icon.src);
const imageVersion=read('js/graphics/coin-reference.js').toString().match(/webp\?v=([\d.]+)/)[1];
for(const name of fs.readdirSync(path.join(root,'assets/coins')).filter(n=>n.endsWith('.webp')))add('assets/coins/'+name+'?v='+imageVersion);
const assets=[...urls].sort().map(url=>{const bytes=read(url.split('?')[0]);return {url,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')};});
const worker=read('scripts/offline-worker.js');
const id=createHash('sha256').update(JSON.stringify(assets)).update(worker).digest('hex').slice(0,16);
const output='// Generated by npm run build:offline. Do not edit.\nconst RELEASE = '+JSON.stringify({version,id,assets},null,2)+';\n'+worker;
if(process.argv.includes('--check')) {
  if(!fs.existsSync(path.join(root,'sw.js')) || read('sw.js').toString()!==output)throw new Error('Stale offline bundle. Run npm run build:offline.');
} else fs.writeFileSync(path.join(root,'sw.js'),output);
console.log(`Offline ${version}: ${assets.length} resources, ${(assets.reduce((n,a)=>n+a.bytes,0)/1024/1024).toFixed(2)} MiB, ${id}`);
